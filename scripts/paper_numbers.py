import sys
from collections import Counter
from pathlib import Path
from types import SimpleNamespace

ROOT = Path(__file__).resolve().parent.parent
sys.path[:0] = [str(ROOT / "src"), str(ROOT / "scripts")]

import compare_versions as cv  # noqa: E402

import refmon  # noqa: E402
from refmon import labreport  # noqa: E402
from refmon.calculus import evidence as calc  # noqa: E402
from refmon.evalstats import wilson_interval  # noqa: E402
from refmon.policy import default_policy  # noqa: E402

VERSION = "v2.4"  # the evaluated version (a tag)
SEED = 335384967  # its seed (docs/variant-seeds.md)
DATA = ROOT / "docs" / "evaluation"
OUT = ROOT / "documentation" / "numbers.tex"


def pct(k: int, n: int) -> str:
    return f"{100 * k / n:.1f}" if n else "0.0"


def wilson(k: int, n: int) -> tuple[str, str]:
    lo, hi = wilson_interval(k, n)
    return f"{100 * lo:.1f}", f"{100 * hi:.1f}"


class Macros:
    def __init__(self) -> None:
        self.items: list[tuple[str, str, str]] = []

    def add(self, name: str, value, note: str = "") -> None:
        if not re.fullmatch(r"[A-Za-z]+", name):
            raise ValueError(f"a macro name has letters only: {name}")
        self.items.append((name, str(value), note))

    def rate(self, name: str, k: int, n: int) -> None:
        """name (count), nameN (of), namePct, nameLo, nameHi (Wilson 95 %)."""
        lo, hi = wilson(k, n)
        self.add(name, k)
        self.add(name + "N", n)
        self.add(name + "Pct", pct(k, n))
        self.add(name + "Lo", lo)
        self.add(name + "Hi", hi)

    def render(self) -> str:
        lines = [
            "% Generated by scripts/paper_numbers.py. Do not edit: re-run the script.",
            f"% Version {VERSION}, seed {SEED}, refmon {refmon.__version__}.",
        ]
        for name, value, note in self.items:
            comment = f"  % {note}" if note else ""
            lines.append(f"\\newcommand{{\\{name}}}{{{value}}}{comment}")
        return "\n".join(lines) + "\n"


def tex(text: str) -> str:
    """Text for a LaTeX table cell (command text in \\texttt)."""
    repl = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
            "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\^{}",
            "|": r"\textbar{}"}  # fmt: skip
    return "".join(repl.get(ch, ch) for ch in text)


def variants(m: Macros) -> dict:
    rows = cv.load(str(DATA / f"{VERSION}-seed-{SEED}.jsonl"))
    allr = list(rows.values())
    mal = [r for r in allr if r.get("kind", "malicious") == "malicious"]
    neutral = [r for r in allr if r.get("kind") == "benign" and not r.get("adds")]
    added = [r for r in allr if r.get("kind") == "benign" and r.get("adds")]
    if len(mal) + len(neutral) + len(added) != len(allr):
        raise SystemExit("the variant groups do not add up")
    out = Counter(cv.outcome(r) for r in mal)
    m.add("VarTotal", len(allr), "all variants of the seed")
    m.add("MalTotal", len(mal))
    m.add("MalBlock", out["block"])
    m.add("MalEffHold", out["effective hold"])
    m.add("MalHoldNothing", out["hold pauses nothing"])
    m.add("MalAllow", out["allow"])
    m.add("MalUncontained", out["allow"] + out["hold pauses nothing"])
    m.rate("MalContained", out["block"] + out["effective hold"], len(mal))
    m.rate("MalBlocked", out["block"], len(mal))
    m.rate("MalCaught", len(mal) - out["allow"], len(mal))
    seeded = [r for k, r in rows.items() if cv.seeded(k, r) and r in mal]
    so = Counter(cv.outcome(r) for r in seeded)
    m.rate("MalSeededContained", so["block"] + so["effective hold"], len(seeded))
    for name, group in (("Neutral", neutral), ("Added", added)):
        by = Counter(r["decision"] for r in group)
        m.add(f"Ben{name}Total", len(group))
        m.add(f"Ben{name}Allow", by["allow"])
        m.add(f"Ben{name}Hold", by["hold"])
        m.add(f"Ben{name}Block", by["block"])
        m.rate(f"Ben{name}BlockRate", by["block"], len(group))
        m.rate(f"Ben{name}AllowRate", by["allow"], len(group))
    m.add("BenNeutralHoldByDesign", sum(r["decision"] == "hold" == r["expected"] for r in neutral))
    m.add("BenNeutralHoldWorse",
          sum(r["decision"] == "hold" and r["expected"] == "allow" for r in neutral))  # fmt: skip
    contract = [r for r in added if "contract" in (r.get("adds") or [])]
    effect = [r for r in added if "contract" not in (r.get("adds") or [])]
    for name, group in (("AddedContract", contract), ("AddedEffect", effect)):
        by = Counter(r["decision"] for r in group)
        m.add(f"Ben{name}Total", len(group))
        for d in ("allow", "hold", "block"):
            m.add(f"Ben{name}{d.capitalize()}", by[d])
    m.add("BenTotal", len(neutral) + len(added))
    return {"mal": mal, "neutral": neutral}


def golden(m: Macros) -> None:
    from refmon.golden import load_golden_cases
    from refmon.keys import LAB_REPLAY_KEY
    from refmon.pipeline import Pipeline
    from refmon.replay import ReplaySource

    policy = default_policy()
    cases = load_golden_cases(ROOT / "tests" / "golden")
    ok = rule_ok = 0
    kinds: Counter[str] = Counter()
    for c in cases:
        pipe = Pipeline(policy, key=LAB_REPLAY_KEY)
        for e in ReplaySource(c.events_path, extra_roles=policy.extra_roles):
            pipe.process(e)
        best = pipe.best()
        decision = best.decision.value if best else "allow"
        rule = best.rule_decision.value if best else "allow"
        ok += decision == c.expected.decision.value
        rule_ok += rule == c.expected.rule_decision.value
        kinds[c.expected.kind.value] += 1
    m.add("GoldenTotal", len(cases))
    m.add("GoldenOk", ok, "final decision as expected")
    m.add("GoldenRuleOk", rule_ok, "3/2/1 rule decision as expected")
    m.add("GoldenMalicious", kinds["malicious"])
    m.add("GoldenBenign", kinds["benign"])


def lab(m: Macros) -> None:
    doc = json.loads((DATA / f"lab-reference-run-{VERSION}.json").read_text(encoding="utf-8"))
    rs = doc["results"]
    attacks = [r for r in rs if r["kind"] == "stop"]
    benign = [r for r in rs if r["kind"] == "allow"]
    limits = [r for r in rs if r["kind"] == "miss"]
    controls = [r for r in rs if r["kind"] == "control"]
    templates = attacks + benign + limits
    m.add("LabTemplates", len(templates), "attack, benign and known-limit templates")
    m.add("LabAttacks", len(attacks))
    m.add("LabLimits", len(limits))
    m.add("LabAttacksAll", len(attacks) + len(limits), "attacks including the known limit")
    m.add("LabDetected", sum(r["decision"] != "allow" for r in attacks + limits))
    m.add("LabStopped", sum(bool(r["stopped_by_refmon"]) for r in attacks))
    m.add("LabBlocked", sum(r["decision"] == "block" for r in attacks))
    m.add("LabBenign", len(benign))
    m.add("LabBenignAllowed", sum(r["decision"] == "allow" for r in benign))
    m.add("LabControls", len(controls))
    for name, group in (("Web", "control-web"), ("Typed", "control-typed")):
        rows = [r for r in controls if r["category"] == group]
        by = Counter(r["decision"] for r in rows)
        m.add(f"Ctl{name}Total", len(rows))
        for d in ("allow", "hold", "block"):
            m.add(f"Ctl{name}{d.capitalize()}", by[d])
    ms = sorted(r["judge_ms"] for r in templates)
    m.add("LabMedianMs", f"{statistics.median(ms):.1f}")
    m.add("LabMaxMs", f"{max(ms):.1f}")
    m.add("LabUnderTenMs", sum(x < 10 for x in ms))
    meta = doc["meta"]
    tb, th = meta["tau_block"], meta["tau_hold"]
    scored = [r for r in attacks if r["decision"] != "allow" and not r["override"]]
    m.add("LabScored", len(scored), "score-based blocks (no override)")
    m.add("LabMeanMargin", f"{statistics.mean(r['log_odds'] - tb for r in scored):.2f}")
    recs = [SimpleNamespace(**r) for r in scored]
    worst = [labreport._worst_single_removal(r, meta["weights"], tb, th) for r in recs]
    m.add("LabAblSilent", sum(1 for w in worst if w and w[0] == "ALLOW"))
    m.add("LabAblHeld", sum(1 for w in worst if w and w[0] == "HOLD"))
    m.add("LabAblStill", sum(1 for w in worst if not w or w[0] == "BLOCK"))
    if sum(1 for w in worst if w and w[0] in ("ALLOW", "HOLD")) + sum(
        1 for w in worst if not w or w[0] == "BLOCK"
    ) != len(scored):
        raise SystemExit("the ablation classes do not add up")
    m.add("LabOverrides", sum(1 for r in attacks if r["override"]))
    from refmon.attacklab import TEMPLATES

    text = {t.id: t.command for t in TEMPLATES}
    for name, group in (("Web", "control-web"), ("Typed", "control-typed")):
        rows = [r for r in controls if r["category"] == group]
        lines = []
        for r in rows:
            cmd = text[r["template_id"]]
            if any(ch in cmd for ch in "%#{}\\") or len(cmd) > 48:
                cell = (
                    "\\emph{a paragraph of prose}" if len(cmd) > 48 else f"\\texttt{{{tex(cmd)}}}"
                )
            else:
                cell = f"\\path{{{cmd}}}"  # url package: breaks at / . and spaces
            fails = "".join(
                "X" if r[f"{q}_failed"] else "." for q in ("origin", "contract", "effect")
            )
            lines.append(
                f"{cell} & {r['decision'].upper()} & ${r['log_odds']:.2f}$ & "
                f"\\texttt{{{fails}}} \\\\"
            )
        m.add(f"CtlRows{name}", "\n".join(lines))


def falco(m: Macros) -> None:
    """The measured Falco baseline (scripts/falco_baseline.py) on the runnable lab templates."""
    doc = json.loads((DATA / f"falco-baseline-{VERSION}.json").read_text(encoding="utf-8"))
    passes, res = doc["meta"]["passes"], doc["results"]
    m.add("FalcoVersion", doc["meta"]["falco_version"].rsplit(" ", 1)[-1])
    m.add("FalcoRulesStable", passes["stable"]["rules_active"], "Falco's default (stable) rules")
    m.add("FalcoRulesAll", passes["all"]["rules_active"], "stable + incubating + sandbox, active")
    m.add("FalcoRulesAllLoaded", passes["all"]["rules_loaded"])
    ran = [r for r in res if r["ran"]]
    att = [r for r in ran if r["kind"] in ("stop", "miss")]
    ben = [r for r in ran if r["kind"] == "allow"]
    m.add("FalcoRunAttacks", len(att), "runnable attack templates, known limit included")
    m.add("FalcoRunBenign", len(ben))
    m.add("FalcoNotRunAttacks", sum(r["kind"] in ("stop", "miss") for r in res if not r["ran"]))
    m.add("FalcoNotRunControls", sum(r["kind"] == "control" for r in res if not r["ran"]))
    m.add("FalcoSeparAttacks", sum(r["separ_decision"] in ("block", "hold") for r in att))
    m.add("FalcoSeparBenign", sum(r["separ_decision"] in ("block", "hold") for r in ben))
    for p, name in (("stable", "Stable"), ("all", "All")):
        m.add(f"Falco{name}Attacks", sum(bool(r[f"falco_{p}"]) for r in att))
        m.add(f"Falco{name}Benign", sum(bool(r[f"falco_{p}"]) for r in ben))
        m.add(f"Falco{name}Control", passes[p]["positive_control_alerts"])
    lines = []
    for r in ran:
        for h in r["falco_all"]:
            if r["falco_stable"]:
                raise SystemExit("a default-rule hit: the table below assumes there is none")
            what = f"{h['event']}" + (f" {h['l4proto']}/{h['remote_port']}" if h["l4proto"] else "")
            kind = "attack" if r["kind"] in ("stop", "miss") else "benign"
            lines.append(
                f"\\texttt{{{tex(r['template_id'])}}} ({kind}) & {h['rule']} & "
                f"\\texttt{{{tex(h['process'])}}}: {tex(what)} & {r['separ_decision'].upper()} \\\\"
            )
    m.add("FalcoHitRows", "\n".join(lines))


def audit(m: Macros) -> None:
    from refmon.audit import run_audit

    a = run_audit(ROOT / "tests" / "golden")
    m.add("AudStrings", a.strings_scanned)
    m.add("AudRawFindings", len(a.raw_findings))
    m.add("AudFingerprints", a.fingerprints)
    m.add("AudAttempts", a.reversal_attempts)
    m.add("AudReversals", len(a.reversals))
    m.add("AudControl", a.control_reversals, "reversals with the real key (the attack works)")
    m.add("AudReidTries", a.reid_attempts)
    m.add("AudReidOk", len(a.reid_successes))
    m.add("AudPass", "PASS" if a.ok else "FAIL")


def policy_numbers(m: Macros) -> None:
    p = default_policy()
    mm = p.math
    c, h = mm.costs, mm.hold_catch_rate
    m.add("Prior", mm.prior_attack)
    m.add("PriorLogOdds", f"{calc.prior_log_odds(mm.prior_attack):.3f}")
    m.add("CostMiss", f"{c['missed_attack']:g}")
    m.add("CostFalseBlock", f"{c['false_block']:g}")
    m.add("CostHold", f"{c['hold']:g}")
    m.add("HoldCatch", f"{h:g}")
    m.add("TauBlock", f"{calc.block_threshold(c):.3f}", "ln(C_fb / C_miss)")
    m.add("TauHold", f"{calc.hold_threshold(c, h):.3f}", "ln(C_hold / (h C_miss)), as implemented")
    p_star = c["hold"] / (h * c["missed_attack"])
    m.add("TauHoldLogit", f"{math.log(p_star / (1 - p_star)):.3f}", "logit of the same probability")
    hold_at, block_at = calc.expected_cost_boundaries(c, h)
    m.add("ECHold", f"{hold_at:.3f}", "A82 boundary, off by default")
    m.add("ECBlock", f"{block_at:.3f}", "A82 boundary, off by default")
    m.add("HalfLifeMin", f"{p.thresholds.decay_half_life / 60:g}")
    m.add("OriginThreshold", f"{p.thresholds.origin_strength:g}")
    m.add("EntropyMax", f"{mm.entropy_max_bits:g}")
    m.add("Weights", len(mm.weights))
    w = mm.weights
    for key, name in (("origin_external", "WOrigin"), ("contract_external_exec", "WExtExec"),
                      ("contract_web_worker_exec", "WWebWorkerExec"), ("effect_fetch", "WFetch"),
                      ("effect_hide", "WHide"), ("effect_escalate", "WEscalate")):  # fmt: skip
        m.add(name, f"{w[key]:g}")


def seeds(m: Macros) -> None:
    text = (ROOT / "docs" / "variant-seeds.md").read_text(encoding="utf-8")
    table = text.split("## Retired seeds")[0]
    rows = re.findall(r"^\| (\d{9}) \| [^|]* \| \*\*(\w+)\*\*", table, re.M)
    m.add("Seed", SEED)
    m.add("SeedsRecorded", len(rows))
    m.add("SeedsRetired", sum(1 for _, status in rows if status == "retired"))
    m.add("Version", refmon.__version__)
    m.add("EvalTag", VERSION)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default=str(OUT))
    args = parser.parse_args(argv)
    m = Macros()
    seeds(m)
    variants(m)
    golden(m)
    lab(m)
    falco(m)
    audit(m)
    policy_numbers(m)
    Path(args.out).write_text(m.render(), encoding="utf-8")
    print(f"{len(m.items)} numbers written to {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
